export function buildFacePoints() {
  // Return fresh objects each call (callers may mutate, e.g. adding
  // `.id`) without ever touching the shared POINTS source data itself.
  const pts = POINTS.map((p) => ({ x: p.x, y: p.y, group: p.group }));
  pts.forEach((p, i) => {
    p.id = i;
  });
  return pts;
}

// Real mesh edges (see EDGE_INDICES above), resolved to the actual point
// objects a caller passed in — the SAME points array buildFacePoints()
// produced, so identity/id lines up. maxDist/maxPerNode from the old
// nearest-neighbor generator no longer apply (this is a real
// triangulation, not an approximation of one) and are not accepted.
export function buildFaceEdges(points) {
  return EDGE_INDICES.map(([a, b]) => [points[a], points[b]]);
}

