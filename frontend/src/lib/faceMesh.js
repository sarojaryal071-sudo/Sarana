// SaranaFace.jsx/index.css's per-group CSS transforms and the whole
// expression/animation system keep working unmodified.
//
// How POINTS/EDGES were produced (not run at build/runtime — a one-off,
// reproducible extraction, kept here so the provenance is auditable):
//   1. Parse canonical_face_model.obj's 468 vertices + 898 triangles.
