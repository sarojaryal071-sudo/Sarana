//      reads as a real gap instead of a filled patch.
//   4. Project (x, -y) [model space is y-up; SVG is y-down] into this
//      project's existing "0 0 200 240" viewBox convention, centered on
//      (100, 122) to match index.css's pre-existing .mesh-ring circles.
//   5. pupilL/pupilR are synthesized (each eye ring's centroid), same
//      reasoning as Face Cloner's own animator: the base 468-point model
//      has no iris landmarks — Face Cloner animates an "iris point"
//      overlay rather than a mesh vertex, and so does this component
//      (see SaranaFace.jsx's blink/gaze handling, unchanged by this).
//
